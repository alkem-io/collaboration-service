package port

import (
	"context"
	"errors"

	"github.com/google/uuid"
)

var (
	// ErrPreviewFileMissing is a 404 from a scoped lookup or write to an existing row.
	ErrPreviewFileMissing = errors.New("preview file is missing")
	// ErrPreviewFileConflict means a mutation was rejected due to a storage conflict.
	ErrPreviewFileConflict = errors.New("preview file mutation conflicts")
)

// PreviewFile is existing file-service metadata, not a write grant. The
// generator must verify source-bucket ownership and reserved output identity
// before reading or replacing bytes.
type PreviewFile struct {
	ID                uuid.UUID `json:"id"`
	BucketID          uuid.UUID `json:"storageBucketId"`
	AuthorizationID   uuid.UUID `json:"authorizationId"`
	ExternalReference string    `json:"externalReference"`
	ContentHash       string    `json:"externalID"`
	MIME              string    `json:"mimeType"`
	Size              int64     `json:"size"`
	Temporary         bool      `json:"temporaryLocation"`
}

// PreviewFiles is the private storage surface for derivatives.
type PreviewFiles interface {
	// LookupPreviewAsset reads provenance for the saved file UUID.
	LookupPreviewAsset(ctx context.Context, id uuid.UUID) (PreviewFile, error)
	// LookupPreviewSlot never performs a global lookup.
	LookupPreviewSlot(ctx context.Context, bucket uuid.UUID, reference string) (PreviewFile, error)
	// ReadPreviewAsset addresses only immutable bytes by a verified content hash.
	ReadPreviewAsset(ctx context.Context, contentHash string, maxBytes int64) ([]byte, error)
	// ReplacePreview writes generated bytes to an existing output row or fails.
	ReplacePreview(ctx context.Context, id uuid.UUID, mediaType string, body []byte) error
	// CreatePreview provisions a new private reserved slot. It reports false
	// without changing bytes if a row already owns the bucket-scoped reference.
	CreatePreview(ctx context.Context, bucket uuid.UUID, reference, mediaType string, body []byte) (bool, error)
}
